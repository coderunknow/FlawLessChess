#!/usr/bin/env python3
"""Run and summarize paired FlawLessChess-vs-FlawLessChess relative matches.

This is a screening tool, not an absolute-rating estimator. It uses the repository's
existing UCI match manager (scripts/match.py), python-chess as the referee, paired
color-reversed games, a fixed opening suite, and a seeded opening-order shuffle.
The quick profile is deliberately small; extended runs use more opening clusters and
are aggregated by opening cluster across independent runner jobs.

The match result is reported as a private relative estimate only. It is not CCRL,
CEGT, FIDE, or platform Elo and must not be represented as an official rating.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import platform
import random
import subprocess
import sys
import time
from collections import Counter, defaultdict
from pathlib import Path
from typing import Iterable

import chess

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import stats  # noqa: E402

CANDIDATE_NAME = "candidate"
BASELINE_NAME = "baseline"
HASH_MB = 64
MOVETIME_MS = 100
BOOTSTRAP_REPLICATES = 10_000
SEVERE_REGRESSION_ELO = -50.0
# Opening count each profile requires. "quick" is the 20-opening regression screen, "screen" is
# the same screen with the 100-opening extended suites (used for the ablation variants, where the
# per-variant sample has to be large enough to separate the terms), and "extended" is the
# three-replicate tournament that pools 600 games.
PROFILE_OPENING_COUNTS = {"quick": 20, "screen": 100, "extended": 100}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def write_json(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


def load_opening_suites(paths: list[Path]) -> list[tuple[str, list[str]]]:
    """Load and legally validate each committed ``name|uci moves`` opening line."""
    openings: list[tuple[str, list[str]]] = []
    seen_names: set[str] = set()
    seen_move_lines: set[tuple[str, ...]] = set()
    seen_positions: set[tuple[str, bool, int, int | None]] = set()
    for path in paths:
        if not path.is_file():
            raise ValueError(f"opening suite not found: {path}")
        for line_no, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            raw = raw.strip()
            if not raw or raw.startswith("#"):
                continue
            if "|" not in raw:
                raise ValueError(f"{path}:{line_no}: expected 'name|uci moves'")
            name, moves_text = (part.strip() for part in raw.split("|", 1))
            moves = moves_text.split()
            if not name:
                raise ValueError(f"{path}:{line_no}: opening name is empty")
            if name in seen_names:
                raise ValueError(f"duplicate opening name {name!r} in {path}:{line_no}")
            move_key = tuple(moves)
            if move_key in seen_move_lines:
                raise ValueError(f"duplicate opening move line for {name!r} in {path}:{line_no}")
            board = chess.Board()
            for ply, token in enumerate(moves, start=1):
                try:
                    move = chess.Move.from_uci(token)
                except ValueError as exc:
                    raise ValueError(f"{path}:{line_no}: malformed UCI move {token!r}") from exc
                if move not in board.legal_moves:
                    raise ValueError(
                        f"{path}:{line_no}: illegal move {token!r} at ply {ply} in {board.fen()}"
                    )
                board.push(move)
                if board.is_game_over(claim_draw=True) and ply != len(moves):
                    raise ValueError(f"{path}:{line_no}: continuation after terminal position")
            if not board.is_valid():
                raise ValueError(f"{path}:{line_no}: opening leaves invalid position {board.fen()}")
            position_key = (board.board_fen(), board.turn, board.castling_rights, board.ep_square)
            if position_key in seen_positions:
                raise ValueError(f"{path}:{line_no}: duplicate final board position for {name!r}")
            seen_names.add(name)
            seen_move_lines.add(move_key)
            seen_positions.add(position_key)
            openings.append((name, moves))
    return openings


def shuffled_openings(openings: list[tuple[str, list[str]]], seed: int) -> list[tuple[str, list[str]]]:
    result = list(openings)
    random.Random(seed).shuffle(result)
    return result


def write_openings(path: Path, openings: list[tuple[str, list[str]]], seed: int) -> None:
    lines = [
        f"# Seeded order from the committed suite; seed={seed}; color pair is AB then BA.",
        "# Generated by scripts/relative_benchmark.py; do not edit for an individual run.",
    ]
    lines.extend(f"{name}|{' '.join(moves)}" for name, moves in openings)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_jsonl(paths: Iterable[Path]) -> list[dict]:
    rows: list[dict] = []
    for path in paths:
        with path.open(encoding="utf-8") as f:
            for line_no, raw in enumerate(f, start=1):
                if raw.strip():
                    try:
                        rows.append(json.loads(raw))
                    except json.JSONDecodeError as exc:
                        raise ValueError(f"invalid JSONL {path}:{line_no}: {exc}") from exc
    return rows


def validate_run_records(records: list[dict], expected_openings: list[str]) -> list[str]:
    errors: list[str] = []
    expected_games = len(expected_openings) * 2
    if len(records) != expected_games:
        errors.append(f"expected {expected_games} game records, found {len(records)}")
    by_opening: dict[str, list[dict]] = defaultdict(list)
    for row in records:
        by_opening[row.get("opening", "<missing>")].append(row)
        if row.get("counted") is not True:
            errors.append(f"uncounted game at schedule index {row.get('schedule_index')}")
        if row.get("engine_error"):
            errors.append(f"engine error at schedule index {row.get('schedule_index')}")
        if row.get("adjudicated") is False or row.get("result") not in ("1-0", "0-1", "1/2-1/2"):
            errors.append(f"unadjudicated game at schedule index {row.get('schedule_index')}")
        if {row.get("white"), row.get("black")} != {CANDIDATE_NAME, BASELINE_NAME}:
            errors.append(f"unexpected engine names at schedule index {row.get('schedule_index')}")
    expected_set = set(expected_openings)
    if set(by_opening) != expected_set:
        errors.append(
            f"opening identity mismatch: missing={sorted(expected_set - set(by_opening))}, "
            f"unexpected={sorted(set(by_opening) - expected_set)}"
        )
    for name in expected_openings:
        pair = by_opening.get(name, [])
        if len(pair) != 2:
            errors.append(f"opening {name!r} has {len(pair)} games, expected a color-reversed pair")
            continue
        colors = {(g.get("color_pair"), g.get("white"), g.get("black")) for g in pair}
        wanted = {
            ("AB", CANDIDATE_NAME, BASELINE_NAME),
            ("BA", BASELINE_NAME, CANDIDATE_NAME),
        }
        if colors != wanted:
            errors.append(
                f"opening {name!r} is not exactly AB/BA color-reversed: {sorted(map(repr, colors))}"
            )
    return errors


def _elo(score: float) -> float | None:
    if score <= 0.0 or score >= 1.0:
        return None
    return stats.elo_from_score(score)


def _display_elo(value: float | None, boundary_score: float) -> str:
    if value is not None:
        return f"{value:+.1f}"
    return "-infinity (zero score boundary)" if boundary_score <= 0.0 else "+infinity (perfect score boundary)"


def summarize_records(
    records: list[dict],
    expected_openings: list[str] | None,
    bootstrap_seed: int,
    bootstrap_replicates: int = BOOTSTRAP_REPLICATES,
) -> dict:
    errors = validate_run_records(records, expected_openings) if expected_openings is not None else []
    wdl = Counter()
    score_sum = 0.0
    scorable: list[dict] = []
    for row in records:
        result = row.get("result")
        if (
            row.get("counted") is not True
            or row.get("engine_error")
            or row.get("adjudicated") is False
            or result not in ("1-0", "0-1", "1/2-1/2")
        ):
            continue
        if row.get("white") == CANDIDATE_NAME:
            candidate_score = 1.0 if result == "1-0" else 0.0 if result == "0-1" else 0.5
        elif row.get("black") == CANDIDATE_NAME:
            candidate_score = 1.0 if result == "0-1" else 0.0 if result == "1-0" else 0.5
        else:
            errors.append(f"candidate missing from game at schedule index {row.get('schedule_index')}")
            # The row is left out of the scorable set as well, so the confidence interval is
            # computed over exactly the games the point estimate was computed over.
            continue
        score_sum += candidate_score
        wdl["W" if candidate_score == 1.0 else "L" if candidate_score == 0.0 else "D"] += 1
        scorable.append(row)
    games = sum(wdl.values())
    if games == 0:
        score_fraction = 0.5
        score_ci = [0.0, 1.0]
        score_sd = None
        errors.append("no scorable games")
    else:
        score_fraction = score_sum / games
        _by_opening, clusters = stats.analyze(scorable, CANDIDATE_NAME)
        _point, low, high, score_sd = stats.bootstrap_ci(
            clusters, bootstrap_replicates, bootstrap_seed
        )
        score_ci = [low, high]

    elo_estimate = _elo(score_fraction)
    elo_low = _elo(score_ci[0])
    elo_high = _elo(score_ci[1])
    if score_ci[1] <= 0.0 or (elo_high is not None and elo_high < SEVERE_REGRESSION_ELO):
        classification = "SEVERE_REGRESSION"
    elif elo_low is not None and elo_low > 0.0:
        classification = "POSITIVE_RELATIVE_SIGNAL_SCREENING_ONLY"
    elif score_ci[1] < 0.5:
        classification = "NEGATIVE_RELATIVE_SIGNAL_NOT_SEVERE"
    else:
        classification = "INCONCLUSIVE"

    return {
        "valid": not errors,
        "validation_errors": errors,
        "candidate": CANDIDATE_NAME,
        "baseline": BASELINE_NAME,
        "games": games,
        "opening_clusters": len({r.get("opening") for r in scorable}),
        "wdl": {key: int(wdl[key]) for key in ("W", "D", "L")},
        "score": {
            "points": round(score_sum, 3),
            "fraction": score_fraction,
            "percent": 100.0 * score_fraction,
            "ci95_cluster_bootstrap": score_ci,
            "bootstrap_sd_fraction": score_sd,
        },
        "relative_elo": {
            "estimate": elo_estimate,
            "ci95": [elo_low, elo_high],
            "display": [
                _display_elo(elo_low, score_ci[0]),
                _display_elo(elo_high, score_ci[1]),
            ],
            "model": "logistic transform of score fraction; descriptive relative estimate only",
        },
        "ci_method": {
            "name": "percentile cluster bootstrap over opening positions",
            "replicates": bootstrap_replicates,
            "seed": bootstrap_seed,
            "cluster_unit": "opening name, retaining all color-reversed games and replicate games",
            "limitations": [
                "short fixed movetime is not a calibrated tournament time control",
                "opening-cluster bootstrap uncertainty can be wide with few clusters",
                "this comparison does not estimate absolute platform or official Elo",
                "the quick profile is a regression screen, not a strength gate",
            ],
        },
        "classification": classification,
        "severe_regression_threshold_elo": SEVERE_REGRESSION_ELO,
        "severe_regression": classification == "SEVERE_REGRESSION",
    }


def _cpu_model() -> str | None:
    try:
        for line in Path("/proc/cpuinfo").read_text(errors="replace").splitlines():
            if line.lower().startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or None


def run_benchmark(args: argparse.Namespace) -> int:
    out = Path(args.out).resolve()
    if out.exists():
        raise SystemExit(f"refusing to overwrite existing benchmark evidence directory: {out}")

    suite_paths = [Path(p).resolve() for p in args.opening_suite]
    openings = load_opening_suites(suite_paths)
    expected_openings = PROFILE_OPENING_COUNTS[args.profile]
    if len(openings) != expected_openings:
        raise SystemExit(
            f"{args.profile} requires exactly {expected_openings} unique legal openings; found {len(openings)}"
        )
    ordered = shuffled_openings(openings, args.seed)

    candidate = Path(args.candidate).resolve()
    baseline = Path(args.baseline).resolve()
    for label, binary in (("candidate", candidate), ("baseline", baseline)):
        if not binary.is_file() or not os.access(binary, os.X_OK):
            raise SystemExit(f"{label} binary is missing or not executable: {binary}")
        if any(ch.isspace() for ch in str(binary)):
            raise SystemExit(f"match.py command parsing does not support whitespace in binary paths: {binary}")

    baseline_sha = args.baseline_sha or os.environ.get("BASELINE_SHA")
    candidate_sha = args.candidate_sha or os.environ.get("CANDIDATE_SHA")
    if baseline_sha and baseline_sha != "6ab5b3349264c6c0a740c433ce454f8e1fed698a":
        raise SystemExit(f"benchmark baseline SHA is not the frozen reference: {baseline_sha}")
    for label, sha in (("candidate", candidate_sha), ("baseline", baseline_sha)):
        if sha and (len(sha) != 40 or any(c not in "0123456789abcdefABCDEF" for c in sha)):
            raise SystemExit(f"{label} commit must be a full 40-character SHA: {sha!r}")

    out.mkdir(parents=True, exist_ok=False)
    used_path = out / "openings.used.txt"
    write_openings(used_path, ordered, args.seed)
    bootstrap_seed = args.seed ^ 0x5EED2026
    manifest = {
        "schema": 1,
        "kind": "relative_engine_match",
        "status": "in_progress",
        "profile": args.profile,
        "candidate_commit": candidate_sha,
        "baseline_commit": baseline_sha,
        "baseline_reference": "6ab5b3349264c6c0a740c433ce454f8e1fed698a",
        "seed": args.seed,
        "randomization": "python random.Random(seed).shuffle of the frozen opening rows; engine itself is deterministic",
        "opening_suites": [
            {"path": str(p), "sha256": sha256_file(p)} for p in suite_paths
        ],
        "opening_order_file": used_path.name,
        "opening_order_sha256": sha256_file(used_path),
        "opening_count": len(openings),
        "games_planned": len(openings) * 2,
        "paired_colors": "one candidate-as-White AB game and one candidate-as-Black BA game per opening",
        "match_manager": "scripts/match.py from the candidate checkout; same code and options manage both binaries",
        "python_chess_version": chess.__version__,
        "rustc": subprocess.run(["rustc", "--version"], check=True, capture_output=True, text=True).stdout.strip(),
        "cargo": subprocess.run(["cargo", "--version"], check=True, capture_output=True, text=True).stdout.strip(),
        "host": {
            "platform": platform.platform(),
            "cpu_model": _cpu_model(),
            "logical_cpus": os.cpu_count(),
        },
        "compile_profile": "Cargo release profile from each source revision (LTO=fat, codegen-units=1)",
        "time_control": {"mode": "fixed UCI movetime", "movetime_ms": MOVETIME_MS},
        "engine_options": {
            "hash_mb": HASH_MB,
            "ponder": False,
            "threads": 1,
            "threads_note": "Both revisions advertise UCI Threads (default 1, maximum 1); --threads 1 is explicitly sent",
        },
        "candidate_binary": {"path": str(candidate), "sha256": sha256_file(candidate)},
        "baseline_binary": {"path": str(baseline), "sha256": sha256_file(baseline)},
        # The ablation mask the candidate engine inherits. It selects which evaluation terms are
        # active, so it is part of the identity of the measured candidate: without it, a full run
        # and an ablated run from the same commit and seed are indistinguishable in the record.
        # The pinned baseline predates the switch and always plays the full evaluation.
        "flawless_ablate": os.environ.get("FLAWLESS_ABLATE", ""),
        "flawless_ablate_applies_to": "candidate only",
        "statistics": {
            "bootstrap_replicates": BOOTSTRAP_REPLICATES,
            "bootstrap_seed": bootstrap_seed,
            "cluster": "opening, retaining both color-reversed games",
            "severe_regression_rule": "fail only if the upper 95% cluster-bootstrap relative-Elo bound is below -50, or if any correctness/provenance validation fails",
        },
        "match_directory": str(out / "match"),
        "started_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }
    manifest_path = out / "manifest.json"
    write_json(manifest_path, manifest)

    match_out = out / "match"
    match_py = ROOT / "scripts" / "match.py"
    match_cmd = [
        sys.executable,
        str(match_py),
        "--white-cmd", f"{candidate} uci",
        "--white-name", CANDIDATE_NAME,
        "--black-cmd", f"{baseline} uci",
        "--black-name", BASELINE_NAME,
        "--white-artifact", str(candidate),
        "--black-artifact", str(baseline),
        "--openings", str(used_path),
        "--out", str(match_out),
        "--movetime", str(MOVETIME_MS),
        "--hash", str(HASH_MB),
        "--threads", "1",
        "--repetitions", "1",
        "--max-moves", "300",
        "--max-errors-per-side", "1",
        "--max-replays-per-game", "0",
        "--batch-id", f"relative-{args.profile}-seed-{args.seed}",
    ]
    started = time.monotonic()
    completed = subprocess.run(match_cmd, cwd=ROOT, check=False)
    elapsed = time.monotonic() - started
    games_path = match_out / "games.jsonl"
    records = load_jsonl([games_path]) if games_path.is_file() else []
    validation_errors = validate_run_records(records, [name for name, _moves in ordered])
    match_manifest_path = match_out / "meta.json"
    match_manifest = json.loads(match_manifest_path.read_text()) if match_manifest_path.is_file() else {}
    if match_manifest.get("completion_status") != "completed":
        validation_errors.append(
            f"match manager completion_status={match_manifest.get('completion_status')!r}"
        )
    if match_manifest.get("n_games_counted") != len(openings) * 2:
        validation_errors.append(
            f"match manager counted {match_manifest.get('n_games_counted')!r} games; expected {len(openings) * 2}"
        )
    if match_manifest.get("n_engine_errors") != 0:
        validation_errors.append(f"match manager recorded {match_manifest.get('n_engine_errors')} engine errors")
    if match_manifest.get("n_unadjudicated") != 0:
        validation_errors.append(f"match manager recorded {match_manifest.get('n_unadjudicated')} unadjudicated games")
    if completed.returncode != 0:
        validation_errors.append(f"match.py exited with status {completed.returncode}")

    summary = summarize_records(records, [name for name, _moves in ordered], bootstrap_seed)
    summary["validation_errors"] = list(dict.fromkeys(summary["validation_errors"] + validation_errors))
    summary["valid"] = not summary["validation_errors"]
    summary["elapsed_seconds"] = round(elapsed, 3)
    summary["profile"] = args.profile
    summary["seed"] = args.seed
    summary["candidate_commit"] = manifest["candidate_commit"]
    summary["baseline_commit"] = manifest["baseline_commit"]
    summary["candidate_binary_sha256"] = manifest["candidate_binary"]["sha256"]
    summary["baseline_binary_sha256"] = manifest["baseline_binary"]["sha256"]
    summary_path = out / "summary.json"
    write_json(summary_path, summary)

    manifest["status"] = "completed" if summary["valid"] else "invalid"
    manifest["finished_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    manifest["elapsed_seconds"] = round(elapsed, 3)
    manifest["match_exit_code"] = completed.returncode
    manifest["summary_path"] = str(summary_path)
    write_json(manifest_path, manifest)
    print_summary(summary)
    return 1 if not summary["valid"] or summary["severe_regression"] else 0


def print_summary(summary: dict) -> None:
    score = summary["score"]
    elo = summary["relative_elo"]
    print("\n=== RELATIVE ENGINE BENCHMARK ===")
    print(f"status: {summary['classification']} (valid={summary['valid']})")
    print(f"W/D/L: {summary['wdl']['W']}/{summary['wdl']['D']}/{summary['wdl']['L']} of {summary['games']}")
    print(f"score: {score['points']:.1f}/{summary['games']} = {score['percent']:.1f}%")
    print(f"relative Elo estimate (not absolute/official): {elo['display'][0]} to {elo['display'][1]} 95% CI")
    print(f"opening clusters: {summary['opening_clusters']}; method: {summary['ci_method']['name']}")
    if summary["validation_errors"]:
        print("validation errors:")
        for err in summary["validation_errors"]:
            print(f"  - {err}")
    else:
        print("Evidence limitation: this short fixed-movetime result is screening evidence only.")
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write("## Relative engine benchmark\n\n")
            f.write(f"- **Classification:** `{summary['classification']}` (valid `{summary['valid']}`)\n")
            f.write(f"- **W/D/L:** {summary['wdl']['W']}/{summary['wdl']['D']}/{summary['wdl']['L']} of {summary['games']}\n")
            f.write(f"- **Score:** {score['points']:.1f}/{summary['games']} = {score['percent']:.1f}%\n")
            f.write(f"- **Relative Elo model:** {elo['display'][0]} to {elo['display'][1]} (opening-clustered 95% CI; not official or absolute)\n")
            f.write(f"- **Clusters / elapsed:** {summary['opening_clusters']} openings / {summary.get('elapsed_seconds', 0):.1f}s\n")
            f.write("- **Interpretation:** screening only; inconclusive is not a pass for strength improvement.\n")
            for err in summary["validation_errors"]:
                f.write(f"- **Validation error:** {err}\n")


def aggregate_runs(args: argparse.Namespace) -> int:
    root = Path(args.runs_root).resolve()
    out = Path(args.out).resolve()
    if out.exists():
        raise SystemExit(f"refusing to overwrite aggregate evidence directory: {out}")
    out.mkdir(parents=True, exist_ok=False)
    manifest_paths = sorted(root.rglob("manifest.json"))
    runs: list[tuple[dict, Path, Path]] = []
    for path in manifest_paths:
        manifest = json.loads(path.read_text(encoding="utf-8"))
        if manifest.get("kind") != "relative_engine_match" or manifest.get("profile") != "extended":
            continue
        match_dir = path.parent / "match"
        games_path = match_dir / "games.jsonl"
        summary_path = path.parent / "summary.json"
        runs.append((manifest, games_path, summary_path))
    validation_errors: list[str] = []
    if len(runs) != 3:
        validation_errors.append(f"expected exactly 3 extended replicate manifests, found {len(runs)}")
    if len({m.get("seed") for m, _g, _s in runs}) != len(runs):
        validation_errors.append("extended replicate seeds are not unique")
    for manifest, games_path, summary_path in runs:
        if manifest.get("status") != "completed":
            validation_errors.append(f"replicate seed {manifest.get('seed')} status is {manifest.get('status')!r}")
        if not games_path.is_file():
            validation_errors.append(f"replicate seed {manifest.get('seed')} missing games.jsonl")
        if not summary_path.is_file():
            validation_errors.append(f"replicate seed {manifest.get('seed')} missing summary.json")
        elif not json.loads(summary_path.read_text()).get("valid"):
            validation_errors.append(f"replicate seed {manifest.get('seed')} summary is invalid")
    candidate_hashes = {m.get("candidate_binary", {}).get("sha256") for m, _g, _s in runs}
    baseline_hashes = {m.get("baseline_binary", {}).get("sha256") for m, _g, _s in runs}
    candidate_commits = {m.get("candidate_commit") for m, _g, _s in runs}
    baseline_commits = {m.get("baseline_commit") for m, _g, _s in runs}
    suite_identities = {
        tuple((row.get("path"), row.get("sha256")) for row in m.get("opening_suites", []))
        for m, _g, _s in runs
    }
    if len(candidate_hashes) != 1 or len(baseline_hashes) != 1:
        validation_errors.append("replicate binaries differ; runs cannot be combined")
    if len(candidate_commits) != 1 or len(baseline_commits) != 1:
        validation_errors.append("replicate source SHAs differ; runs cannot be combined")
    ablate_masks = {m.get("flawless_ablate", "") for m, _g, _s in runs}
    if len(ablate_masks) != 1:
        validation_errors.append(
            f"replicate ablation masks differ ({sorted(ablate_masks)}); runs cannot be combined"
        )
    if len(suite_identities) != 1:
        validation_errors.append("replicate opening-suite identities differ")

    record_paths = [games for _manifest, games, _summary in runs if games.is_file()]
    records = load_jsonl(record_paths) if record_paths else []
    expected_openings = 100
    for manifest, games_path, _summary in runs:
        if games_path.is_file():
            rows = load_jsonl([games_path])
            # Reconstruct expected names from the used, seeded suite saved alongside the manifest.
            # Artifact download relocates each run directory, so resolve the saved suite relative
            # to the run's match/ directory rather than trusting the original runner's absolute path.
            used_file = games_path.parent.parent / manifest.get("opening_order_file", "openings.used.txt")
            if used_file.is_file():
                # The manifest records the digest of the opening order that was actually played.
                # Re-checking it here means a corrupted or swapped file cannot be folded into the
                # pooled result unnoticed.
                recorded_digest = manifest.get("opening_order_sha256")
                actual_digest = sha256_file(used_file)
                digest_ok = not recorded_digest or recorded_digest == actual_digest
                if not digest_ok:
                    validation_errors.append(
                        f"seed {manifest.get('seed')}: opening order digest mismatch "
                        f"(manifest {recorded_digest}, file {actual_digest})"
                    )
                try:
                    names = [name.strip() for name, _moves in load_opening_suites([used_file])]
                except ValueError as exc:
                    # A damaged file is a validation failure, not a crash of the aggregator.
                    validation_errors.append(
                        f"seed {manifest.get('seed')}: cannot read the saved opening order: {exc}"
                    )
                    continue
                validation_errors.extend(
                    f"seed {manifest.get('seed')}: {err}"
                    for err in validate_run_records(rows, names)
                )
            else:
                validation_errors.append(f"replicate seed {manifest.get('seed')} missing openings.used.txt")
    if not runs or len(records) != len(runs) * expected_openings * 2:
        validation_errors.append(
            f"combined game count {len(records)} does not equal {len(runs) * expected_openings * 2}"
        )
    bootstrap_seed = args.bootstrap_seed
    summary = summarize_records(records, None, bootstrap_seed)
    summary["validation_errors"] = list(dict.fromkeys(summary["validation_errors"] + validation_errors))
    summary["valid"] = not summary["validation_errors"]
    summary["profile"] = "extended-aggregate"
    summary["replicates"] = [
        {
            "seed": m.get("seed"),
            "elapsed_seconds": m.get("elapsed_seconds"),
            "status": m.get("status"),
            "games_path": str(games),
        }
        for m, games, _summary in runs
    ]
    summary["candidate_commit"] = next(iter(candidate_commits), None) if len(candidate_commits) == 1 else None
    summary["baseline_commit"] = next(iter(baseline_commits), None) if len(baseline_commits) == 1 else None
    summary["candidate_binary_sha256"] = next(iter(candidate_hashes), None) if len(candidate_hashes) == 1 else None
    summary["baseline_binary_sha256"] = next(iter(baseline_hashes), None) if len(baseline_hashes) == 1 else None
    summary["opening_suite_identities"] = [list(x) for x in suite_identities]
    # The aggregate pools the replicates, so its own elapsed time is the sum of the replicate
    # runtimes; without it the summary reports a meaningless 0.0 s.
    summary["elapsed_seconds"] = round(
        sum(float(m.get("elapsed_seconds") or 0.0) for m, _g, _s in runs), 3
    )
    summary_path = out / "aggregate-summary.json"
    write_json(summary_path, summary)
    print_summary(summary)
    return 1 if not summary["valid"] or summary["severe_regression"] else 0


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    run = sub.add_parser("run", help="build-independent paired benchmark execution")
    run.add_argument("--profile", choices=tuple(PROFILE_OPENING_COUNTS), required=True)
    run.add_argument("--candidate", required=True, help="candidate release UCI binary")
    run.add_argument("--baseline", required=True, help="pinned baseline release UCI binary")
    run.add_argument("--opening-suite", action="append", required=True, help="committed opening file; repeatable")
    run.add_argument("--seed", type=int, required=True, help="deterministic opening-order shuffle seed")
    run.add_argument("--out", required=True, help="new evidence directory; existing directories are never overwritten")
    run.add_argument("--candidate-sha", default=None)
    run.add_argument("--baseline-sha", default=None)
    run.set_defaults(func=run_benchmark)
    aggregate = sub.add_parser("aggregate", help="combine three completed extended replicate artifacts")
    aggregate.add_argument("--runs-root", required=True)
    aggregate.add_argument("--out", required=True)
    aggregate.add_argument("--bootstrap-seed", type=int, required=True)
    aggregate.set_defaults(func=aggregate_runs)
    return parser


def main() -> int:
    args = make_parser().parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
